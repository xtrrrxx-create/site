// Regenerates api/_wm-path.js: the watermark wordmark pre-converted to an SVG
// vector path, so the image proxy needs NO fonts at runtime (Vercel has none,
// which renders SVG <text> as tofu boxes).
//
// Run:  node scripts/gen-watermark-path.mjs
// Needs: a TTF at ./rajdhani.ttf  +  devDependency `text-to-svg`.

import TextToSVG from 'text-to-svg';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

const TEXT = 'https://www.jarvis-finder.com/';
const FONT = path.join(root, 'rajdhani.ttf');

const tts = TextToSVG.loadSync(FONT);
const opt = { x: 0, y: 0, fontSize: 100, anchor: 'left top', kerning: true };
const d = tts.getD(TEXT, opt);
const m = tts.getMetrics(TEXT, opt);

const out =
    `// AUTO-GENERATED by scripts/gen-watermark-path.mjs — do not edit by hand.\n` +
    `// Wordmark "${TEXT}" (Rajdhani SemiBold) as a vector path, fontSize 100.\n` +
    `export const WM_W = ${Math.ceil(m.width)};\n` +
    `export const WM_H = ${Math.ceil(m.height)};\n` +
    `export const WM_PATH = ${JSON.stringify(d)};\n`;

fs.writeFileSync(path.join(root, 'api', '_wm-path.js'), out);
console.log(`Wrote api/_wm-path.js (W=${Math.ceil(m.width)} H=${Math.ceil(m.height)})`);
